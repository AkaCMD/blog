#!/usr/bin/env python3
"""Prepare the blog's self-hosted fonts. Requires fonttools and brotli."""
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile
import hashlib
import json

from fontTools import subset
from fontTools.ttLib import TTFont


PROJECT = Path(__file__).resolve().parent.parent
OUTPUT = PROJECT / "content/media/fonts"
HAN_REVISION = "7889f11bf31170b5d092a083b357c8c8130f89e0"
HAN_ROOT = f"https://raw.githubusercontent.com/adobe-fonts/source-han-serif/{HAN_REVISION}"
LIBRON_ROOT = "https://github.com/nicoverbruggen/libron/releases/download/v0.32"
SOURCES = {
    "han-regular": f"{HAN_ROOT}/SubsetOTF/CN/SourceHanSerifCN-Regular.otf",
    "han-bold": f"{HAN_ROOT}/SubsetOTF/CN/SourceHanSerifCN-Bold.otf",
    "han-license": f"{HAN_ROOT}/LICENSE.txt",
    "libron": f"{LIBRON_ROOT}/Libron_Web.zip",
    "libron-license": "https://raw.githubusercontent.com/nicoverbruggen/libron/v0.32/LICENSE",
}


def download(item):
    name, url = item
    with urlopen(url, timeout=90) as response:
        return name, response.read()


def unicode_ranges(codepoints):
    spans = []
    first = last = None
    for cp in sorted(codepoints):
        if last is not None and cp == last + 1:
            last = cp
            continue
        if first is not None:
            spans.append(f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}")
        first = last = cp
    if first is not None:
        spans.append(f"U+{first:X}" if first == last else f"U+{first:X}-{last:X}")
    return ",".join(spans)


def make_subset(data, codepoints, weight):
    font = TTFont(BytesIO(data), recalcTimestamp=False)
    options = subset.Options()
    options.recalc_timestamp = False
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    cutter = subset.Subsetter(options=options)
    cutter.populate(unicodes=codepoints)
    cutter.subset(font)
    # Source Han reserves its original name for unmodified font files.
    style = "Bold" if weight == 700 else "Regular"
    for record in font["name"].names:
        replacements = {
            1: "Memex Han Serif", 2: style,
            3: f"MemexHanSerif-{style}", 4: f"Memex Han Serif {style}",
            6: f"MemexHanSerif-{style}", 16: "Memex Han Serif", 17: style,
        }
        if record.nameID in replacements:
            record.string = replacements[record.nameID].encode(record.getEncoding())
    font.flavor = "woff2"
    buffer = BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def face(family, filename, weight, style="normal", codepoints=None):
    rule = (
        f'@font-face {{\n    font-family: "{family}";\n'
        f'    src: url("{filename}") format("woff2");\n'
        f"    font-weight: {weight};\n    font-style: {style};\n"
        "    font-display: swap;\n"
    )
    if codepoints is not None:
        rule += f"    unicode-range: {unicode_ranges(codepoints)};\n"
    return rule + "}\n"


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=5) as pool:
        downloads = dict(pool.map(download, SOURCES.items()))
    (OUTPUT / "SourceHanSerif-LICENSE.txt").write_bytes(downloads["han-license"])
    (OUTPUT / "Libron-LICENSE.txt").write_bytes(downloads["libron-license"])
    css = ["/* Generated by scripts/prepare_fonts.py. Font licenses are in this folder. */\n"]
    latin = set()
    with ZipFile(BytesIO(downloads["libron"])) as archive:
        for name in archive.namelist():
            if not name.endswith(".woff2"):
                continue
            filename = Path(name).name
            data = archive.read(name)
            (OUTPUT / filename).write_bytes(data)
            latin.update(TTFont(BytesIO(data)).getBestCmap())
            css.append(face("Libron", filename, 700 if "Bold" in filename else 400,
                            "italic" if "Italic" in filename else "normal"))
    original = TTFont(BytesIO(downloads["han-regular"]))
    characters = set(original.getBestCmap()) - latin
    frequency = Counter()
    for path in sorted((PROJECT / "content").rglob("*.md")):
        frequency.update(ord(char) for char in path.read_text())
    common = {cp for cp, _ in frequency.most_common() if cp in characters}
    common = set(sorted(common, key=lambda cp: (-frequency[cp], cp))[:1536])
    common.update(cp for cp in characters if 0x3000 <= cp <= 0x303F or 0xFF00 <= cp <= 0xFFEF)
    remaining = sorted(characters - common)
    groups = [common] + [set(remaining[i:i + 1024]) for i in range(0, len(remaining), 1024)]
    for label, weight in (("regular", 400), ("bold", 700)):
        for index, codepoints in enumerate(groups):
            filename = f"han-serif-{label}-{index:02}.woff2"
            data = make_subset(downloads[f"han-{label}"], codepoints, weight)
            (OUTPUT / filename).write_bytes(data)
            css.append(face("Memex Han Serif", filename, weight, codepoints=codepoints))
        print(f"Prepared {label}: {len(groups)} character subsets", flush=True)
    (OUTPUT / "fonts.css").write_text("\n".join(css))
    manifest = {
        "sources": SOURCES,
        "source_sha256": {name: hashlib.sha256(data).hexdigest() for name, data in downloads.items()},
        "han_family": "Memex Han Serif",
        "han_character_count": len(characters),
        "han_subsets_per_weight": len(groups),
        "han_common_subset_size": len(common),
    }
    (OUTPUT / "sources.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    main()
